template <class T>
inline void release(T*& p) {
    if (p) {
        p->Release();
        p = nullptr;
    }
}

inline std::string hex(HRESULT hr) {
    char buf[32];
    std::snprintf(buf, sizeof buf, "0x%08lX", (unsigned long)hr);
    return buf;
}

